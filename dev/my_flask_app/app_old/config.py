# フランジ幅ごとの標準設定
#   edge_pitch : 端あき（プレート端 → 最外孔芯）
#   row_pitch  : 外列 → 内列のピッチ（行孔ピッチ）
STAGGER_FLANGE_BASE_BY_WIDTH = {
    100: {"edge_pitch": 20.0,  "row_pitch": 15.0},
    150: {"edge_pitch": 30.0,  "row_pitch": 20.0},
    175: {"edge_pitch": 35.0,  "row_pitch": 25.0},
    200: {"edge_pitch": 40.0,  "row_pitch": 30.0},
    250: {"edge_pitch": 60.0,  "row_pitch": 35.0},
    300: {"edge_pitch": 40.0,  "row_pitch": 40.0},
    400: {"edge_pitch": 100.0, "row_pitch": 50.0},
}

def _make_stagger_tuple_from_width(size: str):
    """
    H 型鋼サイズ文字列（例: '300x300x10x15'）からフランジ幅を取り出し、
    STAGGER_FLANGE_BASE_BY_WIDTH を使って千鳥孔ピッチ
    (外↔外スパン, 外→内ピッチ) のタプルを生成する。
    """
    parts = size.split("x")
    if len(parts) < 2:
        raise ValueError(f"サイズ文字列の形式が不正です: {size}")
    # depth = parts[0] は使わず、2番目をフランジ幅として扱う
    flange_width = int(float(parts[1]))

    base = STAGGER_FLANGE_BASE_BY_WIDTH[flange_width]
    edge = base["edge_pitch"]
    row = base["row_pitch"]

    # 外↔外スパン = フランジ幅 − 端あき×2
    outer_span = flange_width - 2 * edge
    return (outer_span, row)

