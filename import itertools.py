target = 5490
result = []
sizes.sort(reverse=True)

while sizes:
    best_comb = []
    best_sum = 0
    # 最大6個組み合わせまで探索（計算速度調整のため）
    for r in range(1, min(7, len(sizes)+1)):
        for comb in itertools.combinations(sizes, r):
            s = sum(comb)
            if s <= target and s > best_sum:
                best_comb = comb
                best_sum = s
            if best_sum == target:
                break
        if best_sum == target:
            break
    if not best_comb:
        # 1本も選べない場合（残り全てがtargetより大きい）
        best_comb = [sizes[0]]
        best_sum = sizes[0]
    result.append((best_comb, best_sum, target - best_sum))
    # 使った寸法をリストから削除
    for v in best_comb:
        sizes.remove(v)

# 出力
for i, (comb, tsum, amari) in enumerate(result, 1):
    print(f"{i:02d}: 5490-({' + '.join(map(str, comb))}) = 5490-({tsum}) = 余り{amari}")
